private void atualizarTabela() {

    DefaultTableModel modelo = (DefaultTableModel) tblLivros.getModel();
    modelo.setRowCount(0);
    tblLivros.clearSelection();
    String sql = "SELECT * FROM livros ORDER BY titulo ASC";

    try (Connection conexao = Conexao.conectar();
         PreparedStatement comando = conexao.prepareStatement(sql);
         ResultSet resultado = comando.executeQuery()) {

        while (resultado.next()) {

            modelo.addRow(new Object[]{
                resultado.getInt("id"),
                resultado.getString("titulo"),
                resultado.getString("autor"),
                resultado.getString("genero"),
                resultado.getInt("ano_publicacao")
            });
        }

    } catch (SQLException erro) {
        System.out.println("Erro ao carregar livros: " + erro.getMessage());
    }
}

