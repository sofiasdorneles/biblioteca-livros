    private void txtPesquisaKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtPesquisaKeyReleased
  
    String pesquisa = txtPesquisa.getText().trim();

    DefaultTableModel modelo = (DefaultTableModel) tblLivros.getModel();
    modelo.setRowCount(0);

    String sql = "SELECT * FROM livros WHERE titulo LIKE ? OR autor LIKE ? ORDER BY titulo ASC";

    try (Connection conexao = Conexao.conectar();
         PreparedStatement comando = conexao.prepareStatement(sql)) {

        comando.setString(1, "%" + pesquisa + "%");
        comando.setString(2, "%" + pesquisa + "%");

        ResultSet resultado = comando.executeQuery();

        while (resultado.next()) {
            modelo.addRow(new Object[]{
                resultado.getInt("id"),
                resultado.getString("titulo"),
                resultado.getString("autor"),
                resultado.getString("genero"),
                resultado.getInt("ano_publicacao")
            });
        }

    } catch (SQLException erro) {
        System.out.println("Erro ao pesquisar livros: " + erro.getMessage());
    }

    }//GEN-LAST:event_txtPesquisaKeyReleased

