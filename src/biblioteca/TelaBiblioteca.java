    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed

String titulo = txtTitulo.getText().trim();
String autor = txtAutor.getText().trim();
String genero = txtGenero.getText().trim();
String ano = txtAno.getText().trim();

if (titulo.trim().isEmpty() || autor.trim().isEmpty() || ano.trim().isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Preencha os campos obrigatorios!");
    return;
}

int anoNumero;

try {
    anoNumero = Integer.parseInt(ano);

    if (anoNumero < 1 || anoNumero > 2026) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Digite um ano entre 1 e 2026!");
        return;
    }

} catch (NumberFormatException erro) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Digite um ano valido!");
    return;
}
String sql = "INSERT INTO livros (titulo, autor, genero, ano_publicacao) VALUES (?, ?, ?, ?)";

try (Connection conexao = Conexao.conectar();
     PreparedStatement comando = conexao.prepareStatement(sql)) {

    comando.setString(1, titulo);
    comando.setString(2, autor);
    comando.setString(3, genero);
    comando.setInt(4, Integer.parseInt(ano));

    comando.executeUpdate();

    javax.swing.JOptionPane.showMessageDialog(this,
            "Livro cadastrado com sucesso!");

    atualizarTabela();
    
    txtTitulo.setText("");
    txtAutor.setText("");
    txtGenero.setText("");
    txtAno.setText("");

} catch (Exception erro) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Erro ao cadastrar: " + erro.getMessage());
}
        // TODO add your handling code here:
    }//GEN-LAST:event_btnCadastrarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed

int linha = tblLivros.getSelectedRow();

if (linha == -1) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Selecione um livro na tabela!");
    return;
}

int id = (int) tblLivros.getValueAt(linha, 0);

int resposta = javax.swing.JOptionPane.showConfirmDialog(this,
        "Deseja realmente excluir este livro?",
        "Confirmar exclusao",
        javax.swing.JOptionPane.YES_NO_OPTION);

if (resposta == javax.swing.JOptionPane.YES_OPTION) {

    String sql = "DELETE FROM livros WHERE id = ?";

    try (Connection conexao = Conexao.conectar();
         PreparedStatement comando = conexao.prepareStatement(sql)) {

        comando.setInt(1, id);
        comando.executeUpdate();

        javax.swing.JOptionPane.showMessageDialog(this,
                "Livro excluido com sucesso!");

    atualizarTabela();
    txtTitulo.setText("");
    txtAutor.setText("");
    txtGenero.setText("");
    txtAno.setText("");
    } catch (Exception erro) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Erro ao excluir: " + erro.getMessage());
    }
}
        // TODO add your handling code here:
    }//GEN-LAST:event_btnExcluirActionPerformed

